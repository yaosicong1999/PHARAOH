"""Which QC images a run should hold, and which it is missing.

Shared by the CLI launcher and anything else that resumes a run; paths and JSON only,
no GUI and no stage code. Every QC group that is on has a completion notion the
launcher can check on resume, the way Stage 4c's patch manifest already works
(`patch_qc.py`):

  stage1_extras    one LUT (dapi) or threshold mask (he) per role
  stage3_debug     the three `3_dbg_*` images and `3_sampled_overlay.png`
  stage4b_*        `tiles/stage4b_qa_manifest.json`, written by Stage 4b and keyed to
                   `standout_nuclei.json`
  stage7_*         `dense_nucleus_pairs/qc_manifest.json`, written by Stage 7 and keyed
                   to `high_confidence_pairs.csv.gz`

A group that is on but not covered is regenerated by that stage's QC-only mode
(`cli_stage1.py --extras-only`, `cli_stage3.py --qc-only`,
`4b_find_standout_nuclei.py --qa-only`, `cli_stage7.py --qc-only`), which draws from
the saved state and changes nothing the later stages read.

A manifest distinguishes two ways of having nothing to show. A group the level does
not apply to (density pictures on the pairs level) is recorded with no files and is
complete. A group whose inputs were missing when it was drawn (tree pictures for
tiles whose Stage-3 image is gone, point overlays for tiles without a raw tile) is
recorded as *incomplete* with the reason, stays "missing" so the next resume draws
it again, and the launcher reports the reason instead of failing the run.
"""
import hashlib
import json
from pathlib import Path

from my_utils import qc_images_enabled

STAGE4B_MANIFEST = "stage4b_qa_manifest.json"      # under tiles/
STAGE7_MANIFEST = "qc_manifest.json"               # under dense_nucleus_pairs/
STAGE4B_GROUPS = ("stage4b_overlays", "stage4b_density")
STAGE7_GROUPS = ("stage7_anchors", "stage7_tree")


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


# ------------------------------------------------------------------ Stage 1
def stage1_extra(run_dir, side):
    """The one `stage1_extras` image a role gets: a LUT for DAPI, a threshold mask for H&E."""
    suffix = "lut" if side.modality == "dapi" else "threshold_mask"
    return Path(run_dir) / f"1_{side.token}_{suffix}.png"


def stage1_extras_expected(run_dir, roles):
    return [stage1_extra(run_dir, side) for side in (roles.moving, roles.fixed)]


def stage1_extras_missing(run_dir, roles):
    return [path for path in stage1_extras_expected(run_dir, roles) if not path.is_file()]


# ------------------------------------------------------------------ Stage 3
def stage3_debug_expected(run_dir, roles):
    run_dir = Path(run_dir)
    return [
        run_dir / f"3_dbg_{roles.moving.token}_gray.png",
        run_dir / "3_dbg_density_mask.png",
        run_dir / "3_dbg_available_after_erode.png",
        run_dir / "3_sampled_overlay.png",
    ]


def stage3_debug_missing(run_dir, roles):
    return [path for path in stage3_debug_expected(run_dir, roles) if not path.is_file()]


# ------------------------------------------------------------------ manifests
def _manifest_missing(manifest_path, base_dir, groups, key_name, key_path):
    """The groups (of `groups`) that are on and not covered by the manifest.

    Covered means: the manifest exists, its key digest matches the artifact the images
    were drawn from, the group is listed, and every listed file exists. A group listed
    with no files counts as covered -- a level that draws nothing for it (density
    pictures on the pairs level) must not be asked again on every resume.
    """
    wanted = [group for group in groups if qc_images_enabled(group)]
    if not wanted:
        return []
    try:
        record = json.loads(Path(manifest_path).read_text())
        if record.get(key_name) != sha256(key_path):
            return wanted
        covered = record.get("groups", {})
    except (OSError, ValueError, TypeError):
        return wanted
    incomplete = record.get("incomplete", {}) if isinstance(record.get("incomplete"), dict) else {}
    missing = []
    for group in wanted:
        files = covered.get(group)
        if (files is None or group in incomplete
                or not all((Path(base_dir) / name).is_file() for name in files)):
            missing.append(group)
    return missing


def _incomplete_notes(manifest_path, key_path):
    """{group: why} for the groups the current manifest marks incomplete."""
    try:
        record = json.loads(Path(manifest_path).read_text())
        for key in ("standout_sha256", "pairs_sha256"):
            if key in record and record[key] != sha256(key_path):
                return {}
        notes = record.get("incomplete", {})
        return dict(notes) if isinstance(notes, dict) else {}
    except (OSError, ValueError, TypeError):
        return {}


def write_manifest(manifest_path, key_name, key_path, groups_files, incomplete=None):
    """Record the QC files drawn for each group, merging with what an earlier pass
    recorded for other groups against the same artifact.

    `incomplete` maps a group to the reason its pictures could not all be drawn;
    such a group is recorded (with whatever was drawn) but stays missing until a
    later pass draws it without a reason.
    """
    manifest_path = Path(manifest_path)
    record = {key_name: sha256(key_path), "groups": {}, "incomplete": {}}
    try:
        old = json.loads(manifest_path.read_text())
        if old.get(key_name) == record[key_name]:
            if isinstance(old.get("groups"), dict):
                record["groups"].update(old["groups"])
            if isinstance(old.get("incomplete"), dict):
                record["incomplete"].update(old["incomplete"])
    except (OSError, ValueError, TypeError):
        pass
    for group, files in groups_files.items():
        record["groups"][group] = sorted(str(name) for name in files)
        record["incomplete"].pop(group, None)
    for group, note in (incomplete or {}).items():
        record["incomplete"][group] = str(note)
    if not record["incomplete"]:
        del record["incomplete"]
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text(json.dumps(record, indent=2))
    return record


# ------------------------------------------------------------------ Stage 4b
def stage4b_qc_missing(run_dir):
    """Stage-4b QC groups that are on and not drawn for the anchors on disk; [] when
    Stage 4b has not finished (nothing to draw yet)."""
    tiles = Path(run_dir) / "tiles"
    standout = tiles / "standout_nuclei.json"
    if not standout.is_file():
        return []
    return _manifest_missing(tiles / STAGE4B_MANIFEST, tiles, STAGE4B_GROUPS,
                             "standout_sha256", standout)


def stage4b_qc_incomplete(run_dir):
    """{group: why} for Stage-4b groups drawn short of their inputs."""
    tiles = Path(run_dir) / "tiles"
    return _incomplete_notes(tiles / STAGE4B_MANIFEST, tiles / "standout_nuclei.json")


def write_stage4b_manifest(tiles_dir, groups_files, incomplete=None):
    tiles = Path(tiles_dir)
    return write_manifest(tiles / STAGE4B_MANIFEST, "standout_sha256",
                          tiles / "standout_nuclei.json", groups_files, incomplete)


# ------------------------------------------------------------------ Stage 7
def stage7_qc_missing(run_dir):
    """Stage-7 QC groups that are on and not drawn for the pairs on disk; [] when
    Stage 7 has not finished. Files are recorded relative to the run directory."""
    run_dir = Path(run_dir)
    pairs = run_dir / "dense_nucleus_pairs" / "high_confidence_pairs.csv.gz"
    if not pairs.is_file():
        return []
    return _manifest_missing(run_dir / "dense_nucleus_pairs" / STAGE7_MANIFEST, run_dir,
                             STAGE7_GROUPS, "pairs_sha256", pairs)


def stage7_qc_incomplete(run_dir):
    """{group: why} for Stage-7 groups drawn short of their inputs."""
    run_dir = Path(run_dir)
    return _incomplete_notes(run_dir / "dense_nucleus_pairs" / STAGE7_MANIFEST,
                             run_dir / "dense_nucleus_pairs" / "high_confidence_pairs.csv.gz")


def write_stage7_manifest(run_dir, groups_files, incomplete=None):
    run_dir = Path(run_dir)
    return write_manifest(run_dir / "dense_nucleus_pairs" / STAGE7_MANIFEST, "pairs_sha256",
                          run_dir / "dense_nucleus_pairs" / "high_confidence_pairs.csv.gz",
                          groups_files, incomplete)
